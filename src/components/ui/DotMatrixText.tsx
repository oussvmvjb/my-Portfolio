interface DotMatrixTextProps {
  text: string;
  dotSize?: number;
  gap?: number;
  charGap?: number;
  className?: string;
}

export default function DotMatrixText({
  text,
  dotSize = 3,
  gap = 2,
  charGap = 4,
  className = "",
}: DotMatrixTextProps) {
  const chars = useMemo(() => text.toUpperCase().split(""), [text]);
  const pitch = dotSize + gap;
  const charWidth = 5 * pitch;
  const totalWidth = chars.length * (charWidth + charGap) - charGap;
  const height = 7 * pitch;

  return (
    <div className={`inline-block overflow-x-auto max-w-full p-2 rounded-xl bg-surface/50 border border-border/60 ${className}`}>
      <svg
        width={totalWidth}
        height={height}
        viewBox={`0 0 ${totalWidth} ${height}`}
        className="block"
        role="img"
        aria-label={text}
      >
        {chars.map((char, charIdx) => {
          const matrix = FONT_5X7[char] || FONT_5X7[" "];
          const charOffsetX = charIdx * (charWidth + charGap);

          return (
            <g key={charIdx} transform={`translate(${charOffsetX}, 0)`}>
              {Array.from({ length: 7 }).map((_, row) => {
                const rowVal = matrix[row] ?? 0;
                return Array.from({ length: 5 }).map((_, col) => {
                  // bit 4 is leftmost (0x10), bit 0 is rightmost (0x01)
                  const isLit = (rowVal & (1 << (4 - col))) !== 0;
                  const cx = col * pitch + dotSize / 2;
                  const cy = row * pitch + dotSize / 2;

                  return (
                    <circle
                      key={`${row}-${col}`}
                      cx={cx}
                      cy={cy}
                      r={dotSize / 2}
                      className={
                        isLit
                          ? "fill-primary transition-opacity duration-300"
                          : "fill-border/30 dark:fill-border/40"
                      }
                    />
                  );
                });
              })}
            </g>
          );
        })}
      </svg>
    </div>
  );
}
